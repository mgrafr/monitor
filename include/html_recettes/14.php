  &nbsp;&nbsp;&nbsp;<span class="txt1_cuisine">2 ou 3 courgettes</span></div>
<div class="txt1_cuisine" style="margin-top: 5px;margin-left:10px"><img src="$$images/oeufs.webp" style="vertical-align: middle; width:60px;heght:auto" alt=""/>
  &nbsp;&nbsp;&nbsp;&nbsp;1 ou 2 oeufs</div>
<div class="txt1_cuisine" style="margin-left:10px"><img src="$$images/creme-fraiche.webp" style="vertical-align: middle;width:60px;heght:auto" alt=""/>
  &nbsp;&nbsp;&nbsp;20 25 cl de crème fraiche</div>
<div class="txt1_cuisine" style="margin-left:10px"><img src="$$images/gruyere.webp" style="vertical-align: middle;width:60px;heght:auto" alt=""/>
	&nbsp;&nbsp;&nbsp;150-200 g de Gruyère rapé</div>
<div class="txt1_cuisine" style="margin-left:10px"><img src="$$images/sel_poivre.webp" style="vertical-align: middle;width:60px;heght:auto" alt=""/>
	&nbsp;&nbsp;&nbsp;2 pincées de sel, 1 pincée de poivre</div>
<p> <strong>Préparation :</strong><br>- Laver les courgettes, les éplucher en laissant des petites bandes de peau<br>
	- Couper les en rondelles. <br>- Faire bouillir de l'eau saléedans une casserolle et plogerz-y les courgette pendan 5 minutes.
	<br>- Pendant ce temps, mélanger l'(les)oeuf(s) la crème fraiche, 150 g de gruyère rapé, le sel et le poivre.</p>
<p> <strong>Cuisson :</strong>	
	<br>- Préchauffer le four à 200°. <br>- Egouter les courgetteset les disposer dans un plat à gratin. 
	<br>- Parsemer le dessus du reste de gruyère rapé. <br>- Enfourner pour 25 minutes.
	</p>